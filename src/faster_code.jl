function (cs::CodegenState)(expr::Assignment)
    lhs = manual_dispatch_toexpr(expr.lhs, NameState(cs.rewrites))
    # Previously this only generated a block if `Meta.isexpr(lhs, :call)` for inline
    # function declarations. This was changed when CSE variables were made to declare
    # as `local`, since `let` block's don't allow `local` for assignments in the header.
    scs, bm = enter_scope(cs)
    scs(expr.rhs)
    rhs = exit_scope!(scs, bm)
    
    return declare!(cs, lhs, rhs)
end

const ARGNAME_PREFIX = Vector{UInt8}("__argₛᵧₘ")

function add_arg_to_rewrites!(rewrites::Dict{Any, Any}, lhs::BasicSymbolic{T}) where {T}
    rewrites[lhs] = if get(rewrites, :readable_variables, false)::Bool
        Symbol(string(lhs)::String)
    else
        get_numbered_symbol_with_prefix(ARGNAME_PREFIX, hash(lhs))
    end
end

function (cs::CodegenState{T})(l::Let) where {T}
    if all(x->x isa Assignment && !(x.lhs isa DestructuredArgs), l.pairs)
        dargs = Vector{Assignment}(l.pairs)
    else
        dargs = Assignment[]
        for x in l.pairs
            handle_let_pair!(dargs, x, cs)
        end
    end

    if l.let_block
        scs, bm = enter_scope(cs)
        for asg in dargs
            lhs = asg.lhs
            if lhs isa BasicSymbolic{T} && iscall(lhs)
                add_arg_to_rewrites!(scs.rewrites, lhs)
            end
            scs(asg)
        end
        bindings = exit_scope!(scs, bm)

        scs, bm = enter_scope(cs)
        scs(l.body)
        body = exit_scope!(scs, bm)
        result = Expr(:let, bindings, body)
        return declare!(cs, get_misc_identifier(cs), result)
    end
    isempty(dargs) && return cs(l.body)

    for asg in dargs
        lhs = asg.lhs
        if lhs isa BasicSymbolic{T} && iscall(lhs)
            add_arg_to_rewrites!(cs.rewrites, lhs)
        end
        cs(asg)
    end

    return cs(l.body)
end

function (cs::CodegenState{T})(fn::Func) where {T}
    dargs = Union{Assignment, DestructuredArgs}[]
    for arg in fn.args
        if arg isa BasicSymbolic{T}
            add_arg_to_rewrites!(cs.rewrites, arg)
        elseif arg isa Assignment
            lhs = arg.lhs
            if lhs isa BasicSymbolic{T}
                add_arg_to_rewrites!(cs.rewrites, lhs)
            end
        elseif arg isa DestructuredArgs
            push!(dargs, arg)
        end
    end
    for kw in fn.kwargs
        lhs = kw.lhs
        if lhs isa BasicSymbolic{T}
            # Does not use `add_arg_to_rewrites!` because kwarg names matter
            cs.rewrites[lhs] = Symbol(string(lhs)::String)
        end
    end

    scs, bm = enter_scope(cs)
    scs(Let(dargs, fn.body, false))
    body = exit_scope!(scs, bm)

    fn_args = Expr(:tuple)
    if !isempty(fn.kwargs)
        fn_kws = Expr(:parameters)
        for asg in fn.kwargs
            lhs = manual_dispatch_toexpr(asg.lhs, NameState(cs.rewrites))
            asg_cs, bm = enter_scope(cs)
            asg_cs(asg.rhs)
            rhs = exit_scope!(asg_cs, bm)
            push!(fn_kws.args, Expr(:kw, lhs, rhs))
        end
        push!(fn_args.args, fn_kws)
    end

    for arg in fn.args
        if arg isa BasicSymbolic{T}
            push!(fn_args.args, cs.rewrites[arg]::Symbol)
        elseif arg isa Assignment
            asg_cs, bm = enter_scope(cs)
            asg_cs(arg.rhs)
            rhs = exit_scope!(asg_cs, bm)
            lhs = manual_dispatch_toexpr(arg.lhs, NameState(cs.rewrites))
            push!(fn_args.args, Expr(:(=), lhs, rhs))
        elseif arg isa DestructuredArgs
            name = arg.name
            if name isa BasicSymbolic{T}
                push!(fn_args.args, manual_dispatch_toexpr(name, NameState(cs.rewrites)))
            else
                push!(fn_args.args, name::Symbol)
            end
        else
            push!(fn_args.args, manual_dispatch_toexpr(arg, NameState(cs.rewrites)))
        end
    end

    fn_body = Expr(:block)
    append!(fn_body.args, fn.pre)
    push!(fn_body.args, body)
    return declare!(cs, get_misc_identifier(cs), Expr(:function, fn_args, fn_body))
end

"""
Key in `CodegenState.rewrites` that controls whether constants among the scalar writes of
a `SetArray`, of the single-element regions of an `ArrayMaker` and of `array_literal` are
written from tables instead of like the other values (default `true`). See
[`emit_scalar_writes!`](@ref).

The constants are written before the other values, and equal constants together, instead
of in the order of the elements. The result only differs for an output in which distinct
indices share storage, such as a `view` with a repeated index. Which writes have happened
when one of them throws differs as well.
"""
const SCALAR_WRITE_TABLES_KEY = :scalar_write_tables

# A numeric constant that is the value of a single-element region of an `ArrayMaker`. The
# integers `1` and `-1` stand for `one` of the element type and its negation there.
struct ScalarConstant
    value::Number
end

# Whether constants may be taken out of the order of the writes and out of the sight of a
# hook on the left-hand sides.
function scalar_write_tables(cs::CodegenState)
    return get(cs.rewrites, SCALAR_WRITE_TABLES_KEY, true)::Bool &&
        get(cs.rewrites, LHS_HOOK_KEY, nothing) === nothing
end

"""
Key in `CodegenState.rewrites` that makes the single-element regions of an `ArrayMaker` and
the elements of an `array_literal` be written as soon as there are enough of them for a
call of [`batched_setindex!`](@ref), instead of after all of them were evaluated (default
`false`).

Evaluating everything first keeps every value alive until the end of the function. With
thousands of values, each of them needs a place on the stack, which takes the compiler time
that grows faster than their number, and makes the generated code store and reload them.
Writing them as they come avoids both. It changes what the generated function does in
these ways, which is why it has to be asked for:

- **The output must not alias anything the values are computed from.** An element
  evaluated after a write would read what was written.
- As for `SCALAR_WRITE_TABLES_KEY`, distinct indices of the output must not share storage,
  since the order of the writes changes: the constants are written last.
- A value that a later region of an `ArrayMaker` replaces may have been written already.
  It is then converted to the element type and written, where it would otherwise have
  been dropped.
"""
const EAGER_SCALAR_WRITES_KEY = :eager_scalar_writes

eager_scalar_writes(cs::CodegenState) = get(cs.rewrites, EAGER_SCALAR_WRITES_KEY, false)::Bool

"""
Fewest numeric constants among the scalar writes of [`emit_scalar_writes!`](@ref) for them
to be written from tables.
"""
const SCALAR_WRITE_TABLES_MIN = 16

"""
A constant has to repeat at least this often among the scalar writes of
[`emit_scalar_writes!`](@ref) to be written to a list or to ranges of indices instead of
from a table of values.
"""
const SCALAR_WRITE_RUN_MIN = 8

"""
The integer indices of a repeated constant are written as ranges if the ranges average at
least this many indices, and as a list of indices otherwise.
"""
const SCALAR_WRITE_RUN_LENGTH = 8

"""
What the helpers of [`emit_scalar_writes!`](@ref) do with a value before writing it:
`KeepValue()` passes it to `setindex!` as it is, `ConvertToEltype()` converts it to the
element type of the array first. These are types so that the helpers are specialized on
them.
"""
struct KeepValue end
struct ConvertToEltype end
@inline scalar_write_value(::KeepValue, buffer, value) = value
@inline scalar_write_value(::ConvertToEltype, buffer, value) = convert(eltype(buffer), value)

"""
    fill_constant_span!(buffer, value, span, runs, inbounds, conversion)

Write `value` to the indices of `buffer` in each range of `runs`. All of them are in the
range `span`, and every other index in `span` is written afterwards.

For an `Array` the whole of `span` is filled instead, which is one loop instead of one per
range. Other arrays may give meaning to a write that is later overwritten: a structured
matrix rejects some values at some indices and a sparse array allocates.
"""
@noinline function fill_constant_span!(
        buffer::Array, value, span::UnitRange{Int}, runs::Vector{UnitRange{Int}},
        inbounds::Bool, conversion
    )
    if inbounds
        @inbounds for i in span
            buffer[i] = scalar_write_value(conversion, buffer, value)
        end
    else
        for i in span
            buffer[i] = scalar_write_value(conversion, buffer, value)
        end
    end
    return nothing
end
function fill_constant_span!(
        buffer, value, span::UnitRange{Int}, runs::Vector{UnitRange{Int}},
        inbounds::Bool, conversion
    )
    return fill_constant_runs!(buffer, value, runs, inbounds, conversion)
end

"""
    fill_constant_runs!(buffer, value, runs, inbounds, conversion)

Write `value` to the indices of `buffer` in each range of `runs`.
"""
@noinline function fill_constant_runs!(buffer, value, runs::Vector{UnitRange{Int}}, inbounds::Bool, conversion)
    if inbounds
        for run in runs
            @inbounds for i in run
                buffer[i] = scalar_write_value(conversion, buffer, value)
            end
        end
    else
        for run in runs, i in run
            buffer[i] = scalar_write_value(conversion, buffer, value)
        end
    end
    return nothing
end

"""
    fill_constant_at!(buffer, value, idxs, inbounds, conversion)

Write `value` to the indices `idxs` of `buffer`.
"""
@noinline function fill_constant_at!(buffer, value, idxs::Vector, inbounds::Bool, conversion)
    if inbounds
        @inbounds for i in idxs
            buffer[i] = scalar_write_value(conversion, buffer, value)
        end
    else
        for i in idxs
            buffer[i] = scalar_write_value(conversion, buffer, value)
        end
    end
    return nothing
end

"""
    set_constants!(buffer, values, idxs, inbounds, conversion)

Write `values[i]` to index `idxs[i]` of `buffer`.
"""
@noinline function set_constants!(buffer, values::Vector, idxs::Vector, inbounds::Bool, conversion)
    if inbounds
        @inbounds for i in eachindex(values, idxs)
            buffer[idxs[i]] = scalar_write_value(conversion, buffer, values[i])
        end
    else
        for i in eachindex(values, idxs)
            buffer[idxs[i]] = scalar_write_value(conversion, buffer, values[i])
        end
    end
    return nothing
end

"""
    consecutive_runs(idxs)

The sorted distinct integers `idxs` as ranges of consecutive values.
"""
function consecutive_runs(idxs::Vector{Int})
    runs = UnitRange{Int}[]
    isempty(idxs) && return runs
    start = stop = first(idxs)
    for i in Iterators.drop(idxs, 1)
        if i == stop + 1
            stop = i
        else
            push!(runs, start:stop)
            start = stop = i
        end
    end
    push!(runs, start:stop)
    return runs
end

"""
    emit_scalar_writes!(cs, dest, idxs, values, isconst; inbounds, convert_to = nothing, span = nothing, inline_last = true)

Generate the code that writes `values[k]` to index `idxs[k]` of the array `dest`, for
every `k`. This is the one place that decides how many scalar writes are generated, for
`SetArray`, for the single-element regions of an `ArrayMaker` and for `array_literal`.

A value for which `isconst` holds is a constant, which the caller allows to be written
before the other values and together with the constants identical to it. It is either

- an expression, which is evaluated once and written to all the indices it is given for,
  or
- a number. If there are at least `SCALAR_WRITE_TABLES_MIN` of them, they and their
  indices are arrays interpolated into the generated code, so that they cost no statement
  each. Otherwise they are written like the other values.

Any other value is the code of an expression that was already generated. Those are
written in the order given.

Of the numbers written from tables,

- if `span` is given, all indices are integers that together make up that range. The most
  frequent number is then written by [`fill_constant_span!`](@ref), if it takes up at
  least half of the range.
- Another one repeating at least `SCALAR_WRITE_RUN_MIN` times is written to the indices it
  occupies: as ranges if they are integers and mostly consecutive, and as a list
  otherwise.
- The remaining ones are written from one table of values per type.

Only identical (`===`) constants count as a repeat, so every index is written with the
very value given for it: equal numbers of different types, `NaN`s with different payloads
and distinct mutable numbers such as `BigFloat`s stay apart.

# Keyword arguments

- `inbounds`: whether the writes of the generated helpers skip bounds checks. A write
  generated as a statement is left to the `@inbounds` of the caller.
- `convert_to`: `nothing` to pass the values to `setindex!` as they are, with a statement
  for each value that is not written from a table. Otherwise the name of a variable
  holding the element type of `dest`: every value is converted to it before it is
  written, and the values that are not written from tables go through
  [`batched_setindex!`](@ref), `BATCHED_SETINDEX_BATCH_SIZE` at a time, which needs the
  indices to be `CartesianIndex`es.
- `inline_last`: whether the last call of `batched_setindex!` is inlined. One such call
  per function is needed, see the comment where it is done. A caller that writes the
  scalars of one function in several steps asks for it once.

Returns whether a call of `batched_setindex!` was inlined.
"""
function emit_scalar_writes!(
        cs::CodegenState, dest::Symbol, idxs::Vector, values::Vector{Any}, isconst::AbstractVector{Bool};
        inbounds::Bool, convert_to::Union{Nothing, Symbol} = nothing,
        span::Union{Nothing, UnitRange{Int}} = nothing, inline_last::Bool = true
    )
    inlined = false
    numbers = count(k -> isconst[k] && !(values[k] isa Expr), eachindex(values)) >= SCALAR_WRITE_TABLES_MIN
    tabled = Bool[isconst[k] && (numbers || values[k] isa Expr) for k in eachindex(values)]
    if any(tabled)
        conversion = convert_to === nothing ? KeepValue() : ConvertToEltype()
        emit_constant_writes!(cs, dest, idxs[tabled], values[tabled], numbers ? span : nothing, inbounds, conversion)
    end
    rest = findall(!, tabled)
    if convert_to === nothing
        for k in rest
            declare!(cs, Expr(:ref, dest, idxs[k]), values[k])
        end
    else
        batches = collect(Iterators.partition(rest, BATCHED_SETINDEX_BATCH_SIZE))
        for (b, ks) in enumerate(batches)
            idxs_expr = Expr(:tuple)
            call = Expr(:call, batched_setindex!, dest, idxs_expr)
            for k in ks
                push!(idxs_expr.args, idxs[k])
                push!(call.args, Expr(:call, convert, convert_to, values[k]))
            end
            if inline_last && b == length(batches)
                inlined = true
                # The last call is inlined on purpose. If every statement of a function
                # is free of effects other than calls that write to an argument, as it is
                # for one that only computes the values, Julia runs its escape analysis on
                # the function, which takes time quadratic in the number of values read
                # from one array (JuliaLang/julia#65304). An inlined store is an effect.
                call = Expr(:macrocall, GlobalRef(Base, Symbol("@inline")), LineNumberNode(0), call)
            end
            declare!(cs, :_, call)
        end
    end
    return inlined
end

# The writes of the constants `values` to `idxs`, see `emit_scalar_writes!`.
function emit_constant_writes!(
        cs::CodegenState, dest::Symbol, idxs::Vector{I}, values::Vector{Any},
        span::Union{Nothing, UnitRange{Int}}, inbounds::Bool, conversion::Union{KeepValue, ConvertToEltype}
    ) where {I}
    by_value = IdDict{Any, Vector{I}}()
    order = Any[]
    for (idx, val) in zip(idxs, values)
        vidxs = get!(by_value, val) do
            push!(order, val)
            I[]
        end
        push!(vidxs, idx)
    end
    background = nothing
    if span !== nothing
        val = argmax(val -> val isa Expr ? 0 : length(by_value[val]), order)
        vidxs = by_value[val]::Vector{Int}
        # Filling the span writes every index of it, so it has to be mostly this constant.
        if !(val isa Expr) && length(vidxs) >= SCALAR_WRITE_RUN_MIN && 2 * length(vidxs) >= length(span)
            background = Some(val)
            runs = consecutive_runs(sort!(vidxs))
            declare!(cs, :_, Expr(:call, fill_constant_span!, dest, val, span, runs, inbounds, conversion))
        end
    end
    tables = Dict{DataType, Tuple{Vector{Any}, Vector{I}}}()
    table_types = DataType[]
    for val in order
        background !== nothing && something(background) === val && continue
        vidxs = by_value[val]
        if val isa Expr || length(vidxs) >= SCALAR_WRITE_RUN_MIN
            runs = vidxs isa Vector{Int} ? consecutive_runs(sort!(vidxs)) : nothing
            if runs !== nothing && SCALAR_WRITE_RUN_LENGTH * length(runs) <= length(vidxs)
                declare!(cs, :_, Expr(:call, fill_constant_runs!, dest, val, runs, inbounds, conversion))
            else
                # Scattered indices: a range each would cost more than it saves.
                declare!(cs, :_, Expr(:call, fill_constant_at!, dest, val, vidxs, inbounds, conversion))
            end
        else
            VT = typeof(val)
            vals, tidxs = get!(tables, VT) do
                push!(table_types, VT)
                (Any[], I[])
            end
            append!(vals, Iterators.repeated(val, length(vidxs)))
            append!(tidxs, vidxs)
        end
    end
    for VT in table_types
        vals, tidxs = tables[VT]
        declare!(cs, :_, Expr(:call, set_constants!, dest, Vector{VT}(vals), tidxs, inbounds, conversion))
    end
    return nothing
end


"""
    setarray_unwrap(val)

The element `val` of a `SetArray` with its wrappers removed, as `cs(val)` removes them.
"""
function setarray_unwrap(@nospecialize(val))
    while true
        unwrapped = unwrap(val)
        unwrapped === val && break
        val = unwrapped
    end
    return val
end

"""
    setarray_constant(val)

The value code generation gives the element `val` of a `SetArray`, if it is a constant.
"""
setarray_constant(@nospecialize(val)) = unwrap_const(setarray_unwrap(val))

"""
    setarray_constants(cs, elems)

Look for the numeric constants among the `elems` of a `SetArray`. Returns `nothing` if
they are not looked for: writing them from tables takes them out of the order of the
writes, which needs every index to be a distinct integer. Otherwise returns
`(unwrapped, consts, span)`: the value of each element with its wrappers removed, which
is what code has to be generated for, so that no element is unwrapped twice; the constant
or `nothing` for each element, or `nothing` in place of the vector if there are too few
constants for tables; and the range the indices span, or `nothing` if they do not form
one.
"""
function setarray_constants(cs::CodegenState, elems)
    scalar_write_tables(cs) || return nothing
    length(elems) >= SCALAR_WRITE_TABLES_MIN || return nothing
    seen = Set{Int}()
    for (i, elem) in enumerate(elems)
        idx = elem isa AtIndex ? elem.i : i
        idx isa Int || return nothing
        idx in seen && return nothing
        push!(seen, idx)
    end
    unwrapped = Any[]
    consts = Any[]
    for elem in elems
        val = setarray_unwrap(elem isa AtIndex ? elem.elem : elem)
        push!(unwrapped, val)
        c = unwrap_const(val)
        push!(consts, c isa Number ? c : nothing)
    end
    count(!isnothing, consts) >= SCALAR_WRITE_TABLES_MIN || return unwrapped, nothing, nothing
    lo, hi = extrema(seen)
    span = hi - lo + 1 == length(seen) ? (lo:hi) : nothing
    return unwrapped, consts, span
end

function (cs::CodegenState)(ex::SetArray)
    arr = cs(ex.arr)::Symbol
    elems = ex.elems
    # The constants are looked for before code is generated for any element. Elements
    # that can only be iterated once are left to be generated one by one.
    if elems isa AbstractArray && !(elems isa Array)
        elems = collect(elems)
    end
    tabled = elems isa Union{Array, Tuple} ? setarray_constants(cs, elems) : nothing
    values = Any[]
    if tabled === nothing
        idxs = Any[]
        for (i, elem) in enumerate(elems)
            if elem isa AtIndex
                push!(idxs, cs(elem.i))
                push!(values, cs(elem.elem)::Symbol)
            else
                push!(idxs, i)
                push!(values, cs(elem)::Symbol)
            end
        end
        isconst = falses(length(idxs))
        span = nothing
    else
        # Code is generated for the unwrapped values: unwrapping an element again could
        # give something else.
        unwrapped, consts, span = tabled
        idxs = Int[]
        isconst = falses(length(elems))
        for (i, elem) in enumerate(elems)
            push!(idxs, elem isa AtIndex ? elem.i : i)
            if consts !== nothing && consts[i] !== nothing
                push!(values, consts[i])
                isconst[i] = true
            else
                push!(values, cs(unwrapped[i])::Symbol)
            end
        end
    end

    scs, bm = enter_scope(cs)
    # Every element was evaluated above, so the constants can be written first even if
    # `arr` aliases an input.
    emit_scalar_writes!(scs, arr, idxs, values, isconst; inbounds = ex.inbounds, span)
    declare!(scs, get_misc_identifier(cs), ex.return_arr ? arr : nothing)
    body = exit_scope!(scs, bm)
    if ex.inbounds
        body = Expr(:macrocall, nameof(var"@inbounds"), LineNumberNode(0), body)
    end
    return declare!(cs, get_misc_identifier(cs), body)
end

function (cs::CodegenState)(ex::MakeArray)
    _similarto = ex.similarto
    if _similarto isa Type
        similarto = cs(_similarto)
    else
        similarto = declare!(cs, get_misc_identifier(cs), Expr(:call, typeof, cs(_similarto)))
    end
    ndim = ndims(ex.elems)::Int
    elT = ex.output_eltype
    result = Expr(
        :call, create_array, similarto, elT, Expr(:call, Expr(:curly, Val, ndim)),
        Expr(:call, Expr(:curly, Val, size(ex.elems)))
    )
    for x in ex.elems
        push!(result.args, cs(x))
    end
    return declare!(cs, get_misc_identifier(cs), result)
end

function (cs::CodegenState{T})(a::MakeSparseArray{<:SparseMatrixCSC}) where {T}
    I, J, V = findnz(a.array)
    m, n = size(a.array)
    result = Expr(:call, sparse, I, J, cs(Const{T}(V)), m, n)
    return declare!(cs, get_misc_identifier(cs), result)
end

function (cs::CodegenState{T})(a::MakeSparseArray{<:SparseVector}) where {T}
    I, V = findnz(a.array)
    n = length(a.array)
    result = Expr(:call, SparseVector, n, I, cs(Const{T}(V)))
    return declare!(cs, get_misc_identifier(cs), result)
end

function (cs::CodegenState)(a::MakeTuple)
    result = Expr(:tuple)
    for ex in a.elems
        push!(result.args, cs(ex))
    end
    return declare!(cs, get_misc_identifier(cs), result)
end

function (cs::CodegenState)(ex::LiteralExpr)
    declare!(cs, get_misc_identifier(cs), recurse_expr(ex.ex, NameState(cs.rewrites)))
end

function (cs::CodegenState)(f::ForLoop)
    st = NameState(cs.rewrites)
    result = Expr(
        :for, Expr(
            :(=), manual_dispatch_toexpr(f.itervar, st), manual_dispatch_toexpr(f.range, st)
        )
    )
    scs, bm = enter_scope(cs)
    scs(f.body)
    body = exit_scope!(scs, bm)
    push!(result.args, body)
    return declare!(cs, get_misc_identifier(cs), result)
end

function codegen_function!(::Type{Let}, cs::CodegenState{T}, expr::BasicSymbolic{T}, expr_idx::Integer) where {T}
    nbors = Graphs.outneighbors(cs.ir.dependency_graph, expr_idx)
    n = length(nbors)
    body_idx = nbors[n]

    # Codegen each symAssignment as a side effect in order
    for i in 1:n-1
        cs(cs.ir[nbors[i]])
    end

    return codegen!(cs, expr_idx, cs(cs.ir[body_idx]))
end

function codegen_function!(::Type{Assignment}, cs::CodegenState{T}, expr::BasicSymbolic{T}, expr_idx::Integer) where {T}
    nbors = Graphs.outneighbors(cs.ir.dependency_graph, expr_idx)
    lhs_expr = cs.ir[nbors[1]]
    rhs = cs.ir[nbors[2]]

    # Generate the RHS before the LHS in its own scope. If the RHS involves the LHS
    # (e.g. `x ← x + y`) The `x` on the RHS will not generate correctly without this.
    # The scope allows `x + y` to refer to the symbol `x`, and then for the assignment
    # to redefine `x` as the rewrite created below.
    scoped_cs, bm = enter_scope(cs)
    scoped_cs(rhs)
    rhs_result = exit_scope!(scoped_cs, bm)
    # This is intentionally different from normal assignment codegen. That has to be
    # backward compatible, but this comes from `symAssignment` and doesn't. The old
    # version turns `Assignment(x(t), rhs)` into `x(t) = rhs` which is an inline
    # function. `symAssignment` turns it into `var"x(t)" = rhs`, and to declare
    # a function the user can use `symFunc`.
    lhs = add_arg_to_rewrites!(cs.rewrites, lhs_expr)
    return codegen!(cs, expr_idx, Expr(:(=), lhs, rhs_result))
end

function codegen_function!(::Type{Func}, cs::CodegenState{T}, expr::BasicSymbolic{T}, expr_idx::Integer) where {T}
    nbors = Graphs.outneighbors(cs.ir.dependency_graph, expr_idx)
    args_term_idx = nbors[1]
    body_idx = nbors[2]

    args_nbors = Graphs.outneighbors(cs.ir.dependency_graph, args_term_idx)
    n_args = length(args_nbors)
    body = cs.ir[body_idx]

    # We actually want to use a whole now `CodegenState` here. The arguments to this function
    # can be variables already present in the outer code. An expression already generated in `cs`
    # involving these arguments would then point to the outer code instead of something
    # dependent on the argument of this inner closure.
    #
    # Since we're copying the current `rewrites`, arguments passed to the outer function
    # will be available to the closure.
    new_rewrites = copy(cs.rewrites)

    # (name, elems): array param + the element variables to bind inside the body
    dargs_info = Tuple{BasicSymbolic{T}, Vector{BasicSymbolic{T}}}[]

    for i in 1:n_args
        arg = cs.ir[args_nbors[i]]
        @match arg begin
            BSImpl.Sym(;) => begin
                add_arg_to_rewrites!(new_rewrites, arg)
            end
            BSImpl.Term(; f) && if f === DestructuredArgs end => begin
                da_nbors = Graphs.outneighbors(cs.ir.dependency_graph, args_nbors[i])
                name = cs.ir[da_nbors[1]]
                elems = BasicSymbolic{T}[cs.ir[da_nbors[j]] for j in 2:length(da_nbors)]
                add_arg_to_rewrites!(new_rewrites, name)
                push!(dargs_info, (name, elems))
            end
            _ => nothing
        end
    end

    fn_body_block = let block = Expr(:block), expr = block, inner_cs = CodegenState(
            expr, block, cs.ir, new_rewrites
        )
        # Emit destructuring bindings — elem_i = array_param[i] — before the body
        for (name, elems) in dargs_info
            name_sym = inner_cs.rewrites[name]::Symbol
            for (i, elem) in enumerate(elems)
                elem_name = manual_dispatch_toexpr(elem, NameState(inner_cs.rewrites))
                declare!(inner_cs, elem_name, Expr(:ref, name_sym, i))
            end
        end

        inner_cs(body)
        inner_cs.expr
    end

    fn_args = Expr(:tuple)
    for i in 1:n_args
        arg = cs.ir[args_nbors[i]]
        @match arg begin
            BSImpl.Sym(;) => push!(fn_args.args, new_rewrites[arg]::Symbol)
            BSImpl.Term(; f) && if f === DestructuredArgs end => begin
                da_nbors = Graphs.outneighbors(cs.ir.dependency_graph, args_nbors[i])
                name = cs.ir[da_nbors[1]]
                push!(fn_args.args, new_rewrites[name]::Symbol)
            end
            _ => push!(fn_args.args, manual_dispatch_toexpr(arg, NameState(cs.rewrites)))
        end
    end

    result = codegen!(cs, expr_idx, Expr(:function, fn_args, Expr(:block, fn_body_block)))

    return result
end
